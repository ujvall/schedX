"""Phase 3, stage 2: evaluate the FROZEN controllers once on held-out test workloads.

Refuses to run if the config or dataset changed since the controllers were frozen.

Usage:  python scripts/phase3_evaluate.py [--config configs/phase3.json] [--phase2-config configs/phase2.json]
                                          [--artifacts artifacts] [--phase2-reports reports/phase2]
                                          [--reports reports/phase3]

Writes  <reports>/per_workload_test.csv, results.json, summary.md (committed)
"""

import argparse
import json
import sys
from pathlib import Path

import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from schedx.ml import load_model  # noqa: E402
from schedx.phase3 import DEPLOYABLE, REFERENCE, analyze, config_hash, load_split, load_traces, test_stage  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(ROOT / "configs" / "phase3.json"))
    ap.add_argument("--phase2-config", default=str(ROOT / "configs" / "phase2.json"))
    ap.add_argument("--artifacts", default=str(ROOT / "artifacts"))
    ap.add_argument("--phase2-reports", default=str(ROOT / "reports" / "phase2"))
    ap.add_argument("--reports", default=str(ROOT / "reports" / "phase3"))
    args = ap.parse_args()
    cfg3 = json.loads(Path(args.config).read_text(encoding="utf-8"))
    cfg2 = json.loads(Path(args.phase2_config).read_text(encoding="utf-8"))
    artifacts, reports = Path(args.artifacts), Path(args.reports)

    features, split, meta = load_split(artifacts, cfg2)
    frozen = json.loads((reports / "frozen_controller.json").read_text(encoding="utf-8"))
    bundle = joblib.load(artifacts / "phase3" / "controllers.joblib")  # created by phase3_train.py
    chash = config_hash(cfg3, meta["dataset_version"])
    if not (frozen["frozen"] and frozen["config_hash"] == chash == bundle["config_hash"]):
        sys.exit("config/dataset changed since the controllers were frozen; rerun scripts/phase3_train.py")
    q0, controllers = bundle["q0"], bundle["controllers"]

    test_ids = list(split.index[split == "test"])
    traces = load_traces(artifacts, test_ids)
    wl = pd.read_csv(artifacts / "dataset" / "workloads.csv").set_index("workload_id").loc[test_ids]

    # Phase 2 reference: frozen class map + frozen validation-selected Phase 2 model.
    p2 = json.loads((Path(args.phase2_reports) / "metrics.json").read_text(encoding="utf-8"))
    model, mmeta = load_model(artifacts / "models" / f"{p2['main_experiment']['selected_model']}.joblib")
    rows = features[features.workload_id.isin(test_ids) & (features.horizon_k == cfg3["phase2_class_map_horizon"])]
    predicted = pd.Series(model.predict(rows[mmeta["features"]]), index=rows.workload_id.to_numpy())

    long = test_stage(traces, controllers, q0, cfg3, wl["workload_class"], predicted,
                      p2["policy_experiment"]["class_policy_map"])
    info = wl[["workload_class", "n_processes", "burst_cv"]].assign(
        n_jobs=pd.Series({w: sum(len(p.cpu_bursts) for p in procs) for w, procs in traces.items()}))
    results = analyze(long, info, cfg3)
    results = {
        "config_hash": chash,
        "dataset_version": meta["dataset_version"],
        "default_quantum_q0": q0,
        "controllers": frozen["controllers"],
        "phase2_reference": {"model": p2["main_experiment"]["selected_model"],
                             "horizon_k": cfg3["phase2_class_map_horizon"],
                             "class_map": p2["policy_experiment"]["class_policy_map"]},
        "methods": {"deployable": DEPLOYABLE, "reference_not_deployable": REFERENCE},
        **results,
    }
    reports.mkdir(parents=True, exist_ok=True)
    long.merge(info, left_on="workload_id", right_index=True).to_csv(reports / "per_workload_test.csv", index=False)
    (reports / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    (reports / "summary.md").write_text(render(results, frozen), encoding="utf-8")
    print(f"wrote {reports}")


def pct(x: float) -> str:
    return f"{100 * x:+.2f}%"


def ci(c) -> str:
    return f"[{pct(c[0])}, {pct(c[1])}]"


def render(r: dict, frozen: dict) -> str:
    q0 = r["default_quantum_q0"]
    p = r["primary"]
    sig = p["holm_p"] < 0.05 and p["geo_rel_change_ci95"][1] < 0
    lines = [
        "# Phase 3 results (generated by scripts/phase3_evaluate.py)",
        "",
        f"Config hash `{r['config_hash']}`, dataset `{r['dataset_version']}`. Offline simulation on "
        f"{r['n_test_workloads']} held-out synthetic test workloads (CPU-only burst-trace projection). "
        "No OS-level measurement.",
        "",
        f"Best fixed quantum on train+validation: **RR{q0}** (primary baseline and controller default).",
        f"Frozen controller (selected on validation): **{r['controllers']['selected']['label']}**.",
        "",
        "## Primary comparison (pre-specified): adaptive_selected vs best_fixed",
        "",
        f"- Geometric-mean change in average turnaround: **{pct(p['geo_rel_change'])}**, 95% CI "
        f"{ci(p['geo_rel_change_ci95'])}",
        f"- Mean absolute difference: {p['mean_abs_diff']:+.3f} ticks, 95% CI "
        f"[{p['mean_abs_diff_ci95'][0]:+.3f}, {p['mean_abs_diff_ci95'][1]:+.3f}]",
        f"- Better / equal / worse on {p['share_better']:.0%} / {p['share_equal']:.0%} / {p['share_worse']:.0%} "
        "of workloads",
        f"- Wilcoxon signed-rank p = {p['wilcoxon_p']:.4g} (Holm-adjusted {p['holm_p']:.4g}); "
        f"rank-biserial {p['rank_biserial']:+.3f}; Cohen's dz {p['cohens_dz']:+.3f}",
        f"- **Conclusion: {'statistically supported improvement' if sig else 'no statistically supported improvement'}"
        " over the best fixed quantum.**",
        "",
        "Post-hoc sensitivity (added after test evaluation to explain the disagreement between the bootstrap CI "
        "and the pre-specified test; it does not change the conclusion): "
        f"{r['primary_sensitivity_post_hoc']['n_changed']} workloads changed decision "
        f"({r['primary_sensitivity_post_hoc']['n_better']} better, {r['primary_sensitivity_post_hoc']['n_worse']} worse); "
        f"Wilcoxon on changed workloads only p = {r['primary_sensitivity_post_hoc']['wilcoxon_nonzero_only_p']:.3g}; "
        f"sign test p = {r['primary_sensitivity_post_hoc']['sign_test_p']:.3g}. With most pairs tied, Pratt's "
        "zero handling gives the changed workloads nearly equal ranks, so the test behaves almost like a sign "
        "test (14 vs 11); the bootstrap CI of the mean log ratio is driven by gains that are larger than the "
        "losses.",
        "",
        "## All comparisons (average turnaround, paired over test workloads)",
        "",
        "Negative = lower turnaround than the comparator. CIs: paired bootstrap over workloads. "
        "Deployable comparisons are Holm-adjusted as one family.",
        "",
        "| comparison | method mean | comparator mean | geo change | 95% CI | mean Δ ticks | better/equal/worse | Wilcoxon p | Holm p | r_rb |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, c in {**r["deployable_comparisons"], **r["reference_comparisons"]}.items():
        holm_p = f"{c['holm_p']:.3g}" if "holm_p" in c else "— (reference)"
        lines.append(
            f"| {name} | {c['method_mean']:.2f} | {c['baseline_mean']:.2f} | {pct(c['geo_rel_change'])} | "
            f"{ci(c['geo_rel_change_ci95'])} | {c['mean_abs_diff']:+.2f} | "
            f"{c['share_better']:.0%}/{c['share_equal']:.0%}/{c['share_worse']:.0%} | {c['wilcoxon_p']:.3g} | "
            f"{holm_p} | {c['rank_biserial']:+.2f} |"
        )
    lines += ["", "Rows with `phase2_map_true` or `oracle_*` are **not deployable**: they use the true label or "
              "every candidate's outcome.", "",
              "## Share of the best_fixed → oracle gap closed", "",
              "| method | share of gap closed |", "|---|---|"]
    for m, v in r["oracle_gap_closed"].items():
        lines.append(f"| {m} | {'n/a' if v is None else f'{v:.1%}'} |")
    lines += ["", "## Secondary metrics (mean over test workloads)", "",
              "| method | turnaround | waiting | response | throughput | CPU util. | context switches |",
              "|---|---|---|---|---|---|---|"]
    sec = r["secondary_metrics"]
    for m in sec["avg_turnaround"]:
        lines.append(f"| {m} | " + " | ".join(
            f"{sec[k][m]['mean']:.3f}" for k in ("avg_turnaround", "avg_waiting", "avg_response",
                                                 "throughput", "cpu_utilization", "context_switches")) + " |")
    lines += ["", "Throughput and CPU utilization are identical for every work-conserving policy on the same jobs. "
              "Context switches are counted but cost no simulated time.", "",
              "## Breakdown: adaptive_selected vs best_fixed", ""]
    for dim, groups in r["breakdowns"].items():
        lines += [f"**{dim}**", "", "| group | n | geo change | 95% CI | oracle_fixed geo change |", "|---|---|---|---|---|"]
        for g, v in groups.items():
            a = v["adaptive_selected"]
            lines.append(f"| {g} | {v['n']} | {pct(a['geo_rel_change'])} | {ci(a['geo_rel_change_ci95'])} | "
                         f"{pct(v['oracle_fixed']['geo_rel_change'])} |")
        lines.append("")
    lines += ["## Decisions on test workloads", ""]
    for m, d in r["decisions"].items():
        lines.append(f"- {m}: policies {d['policy_counts']}; sources {d['source_counts']}")
    diag = frozen["train_only_diagnostic"]
    lines += [
        "",
        "## Train-only diagnostic (from the fit stage)",
        "",
        f"Spearman correlation with {diag['target']}: true job-burst CV {diag['spearman_true_job_burst_cv_vs_target']:.2f}; "
        f"burst CV observed online at m={diag['after_completions']} {diag['spearman_observed_burst_cv_vs_target']:.2f}; "
        f"true vs observed CV {diag['spearman_true_vs_observed_cv']:.2f}.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
